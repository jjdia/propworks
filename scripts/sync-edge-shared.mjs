#!/usr/bin/env node
// Copies the PURE logic modules the push-reminders Edge Function needs from
// src/lib into supabase/functions/_shared, rewriting extensionless relative
// imports ('./x') to Deno-style ('./x.ts'). Run after editing any of them:
//   node scripts/sync-edge-shared.mjs          (write)
//   node scripts/sync-edge-shared.mjs --check  (CI: fail if out of date)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SHARED = ['types', 'payerSetup', 'chargeStatus', 'rentPush', 'recurringExpenses'];
const HEADER = '// GENERATED by scripts/sync-edge-shared.mjs from src/lib — do not edit here.\n';

export function transform(src) {
  return HEADER + src.replace(/(from\s+['"])(\.\/[A-Za-z0-9_]+)(['"])/g, '$1$2.ts$3');
}

const check = process.argv.includes('--check');
let stale = 0;
for (const name of SHARED) {
  const want = transform(readFileSync(join(root, 'src/lib', `${name}.ts`), 'utf8'));
  const dest = join(root, 'supabase/functions/_shared', `${name}.ts`);
  const have = existsSync(dest) ? readFileSync(dest, 'utf8') : null;
  if (have === want) continue;
  if (check) { console.error(`STALE: ${dest} (run node scripts/sync-edge-shared.mjs)`); stale++; }
  else { writeFileSync(dest, want); console.log(`wrote ${dest}`); }
}
if (check && stale) process.exit(1);
if (check) console.log(`edge _shared up to date (${SHARED.length} files)`);
